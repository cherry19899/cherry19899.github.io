const TRANSLATIONS: Record<LangCode, Translations> = {
  en, ru, uk, de, fr, es, pt, it, tr, ar, hi, zh, ja, ko, vi, id, pl, th, tl, nl, sv, ro, bn,
};

const RTL_LANGS = new Set<LangCode>(['ar']);

const STORAGE_KEY = 'workpro_lang';

function getLang(): LangCode {
  const stored = localStorage.getItem(STORAGE_KEY) as LangCode | null;
  if (stored && TRANSLATIONS[stored]) return stored;
  // Auto-detect from browser
  const nav = navigator.language.split('-')[0] as LangCode;
  if (TRANSLATIONS[nav]) return nav;
  return 'ru';
}

export function setLang(l: LangCode) {
  localStorage.setItem(STORAGE_KEY, l);
  document.documentElement.setAttribute('dir', RTL_LANGS.has(l) ? 'rtl' : 'ltr');
  window.dispatchEvent(new CustomEvent('workpro:langchange'));
}

export function t(): Translations {
  return TRANSLATIONS[getLang()] || en;
}

export function currentLang(): LangCode {
  return getLang();
}

export function isRTL(): boolean {
  return RTL_LANGS.has(getLang());
}

// Apply direction on load
export function applyLangDir() {
  const lang = getLang();
  document.documentElement.setAttribute('dir', RTL_LANGS.has(lang) ? 'rtl' : 'ltr');
}
